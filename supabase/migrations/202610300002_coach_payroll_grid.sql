create table public.coach_payroll_dates (
  id bigint generated by default as identity primary key,
  payroll_month_id bigint not null references public.coach_payroll_months(id) on delete cascade,
  work_date date not null,
  created_at timestamptz not null default now(),
  unique (payroll_month_id, work_date)
);

create table public.coach_payroll_rows (
  id bigint generated by default as identity primary key,
  payroll_month_id bigint not null references public.coach_payroll_months(id) on delete cascade,
  coach_id bigint not null references public.coaches(id) on delete restrict,
  branch_id bigint not null references public.branches(id) on delete restrict,
  hourly_rate numeric(12,2) not null default 0 check (hourly_rate >= 0),
  petrol_day_rate numeric(12,2) not null default 0 check (petrol_day_rate >= 0),
  custom_amount_1 numeric(12,2) not null default 0 check (custom_amount_1 >= 0),
  custom_amount_2 numeric(12,2) not null default 0 check (custom_amount_2 >= 0),
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (payroll_month_id, coach_id, branch_id)
);

create table public.coach_payroll_hours (
  payroll_row_id bigint not null references public.coach_payroll_rows(id) on delete cascade,
  payroll_date_id bigint not null references public.coach_payroll_dates(id) on delete cascade,
  hours numeric(8,2) not null default 0 check (hours >= 0),
  primary key (payroll_row_id, payroll_date_id)
);

create index coach_payroll_dates_month_idx on public.coach_payroll_dates(payroll_month_id, work_date);
create index coach_payroll_rows_month_idx on public.coach_payroll_rows(payroll_month_id, coach_id);
create trigger coach_payroll_rows_touch before update on public.coach_payroll_rows for each row execute function public.touch_updated_at();

alter table public.coach_payroll_dates enable row level security;
alter table public.coach_payroll_rows enable row level security;
alter table public.coach_payroll_hours enable row level security;
create policy coach_payroll_dates_admin_all on public.coach_payroll_dates for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy coach_payroll_rows_admin_all on public.coach_payroll_rows for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy coach_payroll_hours_admin_all on public.coach_payroll_hours for all to authenticated using (public.is_admin()) with check (public.is_admin());

insert into public.coach_payroll_dates (payroll_month_id, work_date)
select distinct payroll_month_id, work_date from public.coach_payroll_entries
on conflict (payroll_month_id, work_date) do nothing;

insert into public.coach_payroll_rows (payroll_month_id, coach_id, branch_id, hourly_rate, petrol_day_rate, custom_amount_1, custom_amount_2)
select payroll_month_id, coach_id, branch_id,
  (array_agg(hourly_rate order by work_date desc, id desc))[1],
  (array_agg(petrol_day_rate order by work_date desc, id desc))[1],
  sum(custom_amount_1), sum(custom_amount_2)
from public.coach_payroll_entries
group by payroll_month_id, coach_id, branch_id
on conflict (payroll_month_id, coach_id, branch_id) do nothing;

insert into public.coach_payroll_hours (payroll_row_id, payroll_date_id, hours)
select payroll_row.id, payroll_date.id, sum(entry.hours)
from public.coach_payroll_entries entry
join public.coach_payroll_rows payroll_row on payroll_row.payroll_month_id = entry.payroll_month_id and payroll_row.coach_id = entry.coach_id and payroll_row.branch_id = entry.branch_id
join public.coach_payroll_dates payroll_date on payroll_date.payroll_month_id = entry.payroll_month_id and payroll_date.work_date = entry.work_date
group by payroll_row.id, payroll_date.id
on conflict (payroll_row_id, payroll_date_id) do update set hours = excluded.hours;

create or replace function public.save_coach_payroll_grid(
  p_pay_month date,
  p_custom_column_1_label text,
  p_custom_column_2_label text,
  p_dates jsonb,
  p_rows jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_month date := date_trunc('month', p_pay_month)::date;
  v_payroll_id bigint;
  v_date jsonb;
  v_date_value date;
  v_date_id bigint;
  v_saved_date_ids bigint[] := '{}';
  v_row jsonb;
  v_row_id bigint;
  v_saved_row_ids bigint[] := '{}';
  v_hours jsonb;
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  if nullif(btrim(p_custom_column_1_label), '') is null or nullif(btrim(p_custom_column_2_label), '') is null then raise exception 'Allowance headers are required'; end if;
  if jsonb_typeof(coalesce(p_dates, '[]'::jsonb)) <> 'array' or jsonb_typeof(coalesce(p_rows, '[]'::jsonb)) <> 'array' then raise exception 'Payroll dates and rows must be arrays'; end if;

  insert into public.coach_payroll_months (pay_month, custom_column_1_label, custom_column_2_label)
  values (v_month, btrim(p_custom_column_1_label), btrim(p_custom_column_2_label))
  on conflict (pay_month) do update set custom_column_1_label = excluded.custom_column_1_label, custom_column_2_label = excluded.custom_column_2_label
  returning id into v_payroll_id;

  for v_date in select value from jsonb_array_elements(coalesce(p_dates, '[]'::jsonb)) loop
    v_date_value := trim(both '"' from v_date::text)::date;
    if v_date_value < v_month or v_date_value >= (v_month + interval '1 month')::date then raise exception 'Every work date must be inside the payroll month'; end if;
    insert into public.coach_payroll_dates (payroll_month_id, work_date) values (v_payroll_id, v_date_value)
    on conflict (payroll_month_id, work_date) do update set work_date = excluded.work_date returning id into v_date_id;
    v_saved_date_ids := array_append(v_saved_date_ids, v_date_id);
  end loop;

  for v_row in select value from jsonb_array_elements(coalesce(p_rows, '[]'::jsonb)) loop
    if not exists(select 1 from public.coaches where id = (v_row ->> 'coach_id')::bigint) then raise exception 'Coach does not exist'; end if;
    if not exists(select 1 from public.branches where id = (v_row ->> 'branch_id')::bigint) then raise exception 'Branch does not exist'; end if;
    v_row_id := nullif(v_row ->> 'id', '')::bigint;
    if v_row_id is null then
      insert into public.coach_payroll_rows (payroll_month_id, coach_id, branch_id, hourly_rate, petrol_day_rate, custom_amount_1, custom_amount_2)
      values (v_payroll_id, (v_row ->> 'coach_id')::bigint, (v_row ->> 'branch_id')::bigint, coalesce((v_row ->> 'hourly_rate')::numeric, 0), coalesce((v_row ->> 'petrol_day_rate')::numeric, 0), coalesce((v_row ->> 'custom_amount_1')::numeric, 0), coalesce((v_row ->> 'custom_amount_2')::numeric, 0))
      returning id into v_row_id;
    else
      update public.coach_payroll_rows set coach_id = (v_row ->> 'coach_id')::bigint, branch_id = (v_row ->> 'branch_id')::bigint, hourly_rate = coalesce((v_row ->> 'hourly_rate')::numeric, 0), petrol_day_rate = coalesce((v_row ->> 'petrol_day_rate')::numeric, 0), custom_amount_1 = coalesce((v_row ->> 'custom_amount_1')::numeric, 0), custom_amount_2 = coalesce((v_row ->> 'custom_amount_2')::numeric, 0)
      where id = v_row_id and payroll_month_id = v_payroll_id;
      if not found then raise exception 'Payroll row does not belong to this month'; end if;
    end if;
    v_saved_row_ids := array_append(v_saved_row_ids, v_row_id);
    delete from public.coach_payroll_hours where payroll_row_id = v_row_id;
    for v_hours in select value from jsonb_array_elements(coalesce(v_row -> 'hours', '[]'::jsonb)) loop
      select id into v_date_id from public.coach_payroll_dates where payroll_month_id = v_payroll_id and work_date = (v_hours ->> 'work_date')::date;
      if v_date_id is null then raise exception 'Hours reference a date outside this payroll'; end if;
      insert into public.coach_payroll_hours (payroll_row_id, payroll_date_id, hours) values (v_row_id, v_date_id, coalesce((v_hours ->> 'hours')::numeric, 0));
    end loop;
  end loop;

  delete from public.coach_payroll_rows where payroll_month_id = v_payroll_id and not (id = any(v_saved_row_ids));
  delete from public.coach_payroll_dates where payroll_month_id = v_payroll_id and not (id = any(v_saved_date_ids));
  return v_payroll_id;
end;
$$;

grant execute on function public.save_coach_payroll_grid(date, text, text, jsonb, jsonb) to authenticated;
