alter table public.coaches
  add column if not exists petrol_day_rate numeric(12,2) not null default 0 check (petrol_day_rate >= 0);

create table public.coach_payroll_months (
  id bigint generated by default as identity primary key,
  pay_month date not null unique check (pay_month = date_trunc('month', pay_month)::date),
  custom_column_1_label text not null default 'Allowance 1' check (char_length(custom_column_1_label) between 1 and 60),
  custom_column_2_label text not null default 'Allowance 2' check (char_length(custom_column_2_label) between 1 and 60),
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.coach_payroll_entries (
  id bigint generated by default as identity primary key,
  payroll_month_id bigint not null references public.coach_payroll_months(id) on delete cascade,
  work_date date not null,
  coach_id bigint not null references public.coaches(id) on delete restrict,
  branch_id bigint not null references public.branches(id) on delete restrict,
  hours numeric(8,2) not null default 0 check (hours >= 0),
  hourly_rate numeric(12,2) not null default 0 check (hourly_rate >= 0),
  petrol_day_rate numeric(12,2) not null default 0 check (petrol_day_rate >= 0),
  custom_amount_1 numeric(12,2) not null default 0 check (custom_amount_1 >= 0),
  custom_amount_2 numeric(12,2) not null default 0 check (custom_amount_2 >= 0),
  salary_amount numeric(12,2) generated always as (round(hours * hourly_rate, 2)) stored,
  total_amount numeric(12,2) generated always as (round(hours * hourly_rate, 2) + petrol_day_rate + custom_amount_1 + custom_amount_2) stored,
  remarks text not null default '',
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index coach_payroll_entries_month_idx on public.coach_payroll_entries(payroll_month_id, work_date, coach_id);
create index coach_payroll_entries_branch_idx on public.coach_payroll_entries(branch_id, work_date);
create trigger coach_payroll_months_touch before update on public.coach_payroll_months for each row execute function public.touch_updated_at();
create trigger coach_payroll_entries_touch before update on public.coach_payroll_entries for each row execute function public.touch_updated_at();

alter table public.coach_payroll_months enable row level security;
alter table public.coach_payroll_entries enable row level security;
create policy coach_payroll_months_admin_all on public.coach_payroll_months for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy coach_payroll_entries_admin_all on public.coach_payroll_entries for all to authenticated using (public.is_admin()) with check (public.is_admin());

create or replace function public.validate_coach_payroll_entry()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_month date;
begin
  select pay_month into strict v_month from public.coach_payroll_months where id = new.payroll_month_id;
  if new.work_date < v_month or new.work_date >= (v_month + interval '1 month')::date then raise exception 'Work date must be inside the payroll month'; end if;
  return new;
end;
$$;

create trigger coach_payroll_entry_validate before insert or update on public.coach_payroll_entries for each row execute function public.validate_coach_payroll_entry();

create or replace function public.save_coach_payroll(p_pay_month date, p_custom_column_1_label text, p_custom_column_2_label text, p_entries jsonb)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_month date := date_trunc('month', p_pay_month)::date;
  v_payroll_id bigint;
  v_entry jsonb;
  v_entry_id bigint;
  v_saved_ids bigint[] := '{}';
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  if nullif(btrim(p_custom_column_1_label), '') is null or nullif(btrim(p_custom_column_2_label), '') is null then raise exception 'Allowance headers are required'; end if;
  if char_length(btrim(p_custom_column_1_label)) > 60 or char_length(btrim(p_custom_column_2_label)) > 60 then raise exception 'Allowance headers must be 60 characters or fewer'; end if;
  if jsonb_typeof(coalesce(p_entries, '[]'::jsonb)) <> 'array' then raise exception 'Payroll entries must be an array'; end if;

  insert into public.coach_payroll_months (pay_month, custom_column_1_label, custom_column_2_label)
  values (v_month, btrim(p_custom_column_1_label), btrim(p_custom_column_2_label))
  on conflict (pay_month) do update set custom_column_1_label = excluded.custom_column_1_label, custom_column_2_label = excluded.custom_column_2_label
  returning id into v_payroll_id;

  for v_entry in select value from jsonb_array_elements(coalesce(p_entries, '[]'::jsonb)) loop
    if (v_entry ->> 'work_date')::date < v_month or (v_entry ->> 'work_date')::date >= (v_month + interval '1 month')::date then raise exception 'Every work date must be inside the payroll month'; end if;
    if not exists(select 1 from public.coaches where id = (v_entry ->> 'coach_id')::bigint) then raise exception 'Coach does not exist'; end if;
    if not exists(select 1 from public.branches where id = (v_entry ->> 'branch_id')::bigint) then raise exception 'Branch does not exist'; end if;

    v_entry_id := nullif(v_entry ->> 'id', '')::bigint;
    if v_entry_id is null then
      insert into public.coach_payroll_entries (payroll_month_id, work_date, coach_id, branch_id, hours, hourly_rate, petrol_day_rate, custom_amount_1, custom_amount_2, remarks)
      values (v_payroll_id, (v_entry ->> 'work_date')::date, (v_entry ->> 'coach_id')::bigint, (v_entry ->> 'branch_id')::bigint, coalesce((v_entry ->> 'hours')::numeric, 0), coalesce((v_entry ->> 'hourly_rate')::numeric, 0), coalesce((v_entry ->> 'petrol_day_rate')::numeric, 0), coalesce((v_entry ->> 'custom_amount_1')::numeric, 0), coalesce((v_entry ->> 'custom_amount_2')::numeric, 0), coalesce(v_entry ->> 'remarks', ''))
      returning id into v_entry_id;
    else
      update public.coach_payroll_entries set work_date = (v_entry ->> 'work_date')::date, coach_id = (v_entry ->> 'coach_id')::bigint, branch_id = (v_entry ->> 'branch_id')::bigint, hours = coalesce((v_entry ->> 'hours')::numeric, 0), hourly_rate = coalesce((v_entry ->> 'hourly_rate')::numeric, 0), petrol_day_rate = coalesce((v_entry ->> 'petrol_day_rate')::numeric, 0), custom_amount_1 = coalesce((v_entry ->> 'custom_amount_1')::numeric, 0), custom_amount_2 = coalesce((v_entry ->> 'custom_amount_2')::numeric, 0), remarks = coalesce(v_entry ->> 'remarks', '')
      where id = v_entry_id and payroll_month_id = v_payroll_id;
      if not found then raise exception 'Payroll entry does not belong to this month'; end if;
    end if;
    v_saved_ids := array_append(v_saved_ids, v_entry_id);
  end loop;

  delete from public.coach_payroll_entries where payroll_month_id = v_payroll_id and not (id = any(v_saved_ids));
  return v_payroll_id;
end;
$$;

grant execute on function public.save_coach_payroll(date, text, text, jsonb) to authenticated;
