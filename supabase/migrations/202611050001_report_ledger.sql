alter table public.classes
  add column if not exists short_label text not null default '';

create table public.student_month_remarks (
  id bigint generated by default as identity primary key,
  branch_id bigint not null references public.branches(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete cascade,
  month date not null check (month = date_trunc('month', month)::date),
  remark text not null default '',
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (student_id, month)
);

create index student_month_remarks_branch_idx on public.student_month_remarks(branch_id, month);

create or replace function public.sync_student_month_remark_branch()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  select branch_id into strict new.branch_id from public.students where id = new.student_id;
  return new;
end;
$$;

create trigger student_month_remarks_branch before insert or update on public.student_month_remarks for each row execute function public.sync_student_month_remark_branch();
create trigger student_month_remarks_touch before update on public.student_month_remarks for each row execute function public.touch_updated_at();

alter table public.student_month_remarks enable row level security;

create policy student_month_remarks_admin_all on public.student_month_remarks for all to authenticated
  using (public.is_admin() and public.can_access_branch(branch_id))
  with check (public.is_admin() and public.can_access_branch(branch_id));
